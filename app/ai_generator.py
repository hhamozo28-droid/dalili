def _num_to_arabic(n: int) -> str:
    """تحويل رقم إلى نص عربي (مثال: 1 → واحد، 2 → اثنان...)"""
    numbers = ["صفر", "واحد", "اثنان", "ثلاثة", "أربعة", "خمسة", "ستة", "سبعة", "ثمانية", "تسعة", "عشرة"]
    return numbers[n] if n < len(numbers) else str(n)


