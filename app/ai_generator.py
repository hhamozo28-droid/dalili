def _build_toc() -> str:
    """بناء جدول المحتويات"""
    toc_items = ""
    for i, title in enumerate(_CHAPTER_TITLES):
        toc_items += f'<li>الفصل {_ROMAN[i]}: {title}</li>\n'
    toc_items += '<li>بطاقات المهارات المهنية</li>\n'
    toc_items += '<li>حلول أوراق التدريب والحالات</li>\n'
    toc_items += '<li>التقويم الذاتي</li>\n'

    return f"""<h2>فهرس المحتويات</h2>
<ol>
{toc_items}</ol>"""


def _build_full_guide(spec: str, subject: str) -> str:
    """بناء دليل المتربص الكامل وفق المنهجية الموحدة"""
    parts = []

    # المقدمة
    parts.append(_build_intro(spec, subject))

    # فهرس المحتويات
    parts.append(_build_toc())

    # 8 فصول
    for chapter_idx in range(8):
        chapter_title = _CHAPTER_TITLES[chapter_idx]
        chapter_content = _CHAPTER_CONTENTS[chapter_idx].format(subject=subject, spec=spec)
        chapter_name = _ROMAN[chapter_idx]

        chapter_html = f"""<h2>الفصل {chapter_name}: {chapter_title}</h2>
<p>{chapter_content}</p>"""

        # 4 أوراق تدريب لكل فصل
        for ws_num in range(1, 5):
            ws_topic = _WORKSHEET_TOPICS[chapter_idx]
            chapter_html += "\n" + _build_worksheet(ws_num, chapter_idx, ws_topic, spec, subject)

        # 2 حالات تطبيقية لكل فصل
        for case_num in range(1, 3):
            case_topic = _CASE_TOPICS[chapter_idx % len(_CASE_TOPICS)]
            chapter_html += "\n" + _build_case(case_num, chapter_idx, case_topic, spec, subject)

        parts.append(chapter_html)

    # بطاقات المهارات المهنية
    skills_html = "<h2>بطاقات المهارات المهنية</h2>\n"
    for skill_num in range(1, len(_SKILL_TITLES) + 1):
        skill_title = _SKILL_TITLES[skill_num - 1]
        skills_html += _build_skill_card(skill_num, skill_title, spec, subject) + "\n"
    parts.append(skills_html)

    # الحلول
    solutions_html = "<h2>حلول أوراق التدريب والحالات</h2>\n"
    for chapter_idx in range(8):
        solutions_html += _build_solutions(chapter_idx) + "\n"
    parts.append(solutions_html)

    # التقويم الذاتي
    assessment_html = """<h2>التقويم الذاتي</h2>
<p>بعد دراسة جميع فصول هذا الدليل، يُقيِّم المتربص نفسه وفق المعايير التالية:</p>
<ol>
<li>هل أستطيع فهم المفاهيم الأساسية لـ """ + subject + """؟</li>
<li>هل أستطيع استخدام الأدوات والوسائل بشكل صحيح؟</li>
<li>هل أستطيع تشخيص الأعطال الشائعة؟</li>
<li>هل أستطيع تطبيق إجراءات الصيانة الدورية؟</li>
<li>هل أستطيع تطبيق قواعد السلامة والصحة المهنية؟</li>
<li>هل أستطيع قراءة المخططات الفنية وتطبيقها؟</li>
</ol>
<p>يُسجل المتربص مستوى إتقانه لكل مهارة: مبتدئ، متقدم، محترف، أو خبير.</p>"""
    parts.append(assessment_html)

    return "\n".join(parts)


def _build_title(spec: str, subject: str) -> str:
    """بناء عنوان مناسب للدليل"""
    templates = [
        f"التكوين المهني: {subject}",
        f"دليل المتربص في {subject}",
        f"{subject} — {spec}",
        f"أساسيات {subject} في مجال {spec}",
        f"التكوين المهني: {subject} — {spec}",
    ]
    return random.choice(templates)


def _generate_builtin_guide(spec: str, subject: str) -> Tuple[str, str]:
    """توليد دليل المتربص الكامل بالمولد المدمج — يتبع المنهجية الموحدة"""
    title = _build_title(spec, subject)
    content = _build_full_guide(spec, subject)
    return title, content


